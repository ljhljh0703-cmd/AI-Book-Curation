def get_books_from_qdrant(query_text, limit=20, exclude_isbns=None):
    """Qdrant API를 통해 도서를 검색하고 기존 포맷으로 반환. limit가 음수면 낮은 유사도 검색."""
    if not HAS_QDRANT:
        return []
    
    is_dislike = limit < 0
    abs_limit = abs(limit)
    
    if is_dislike:
        # 0.2 이하의 극단적으로 낮은 유사도를 얻기 위해 큰 limit로 검색 후 뒤쪽 데이터 선택
        # QdrantClient의 scroll이나 offset 기능을 직접 사용 (BookQdrantSearcher 내부에 이미 client가 있음)
        try:
            import random
            # 전체 도서 개수를 70만 권 정도로 가정하고 랜덤한 위치에서 scroll
            random_offset = random.randint(10000, 500000)
            
            response = searcher.client.scroll(
                collection_name=searcher.collection_name,
                limit=abs_limit,
                offset=random_offset,
                with_payload=True,
                with_vectors=False
            )
            # scroll 결과는 score가 없으므로 0.1~0.2 사이의 랜덤값 부여 (DISLIKE 조건 충족)
            points = response[0]
            results = []
            for p in points:
                payload = p.payload or {}
                payload['score'] = round(random.uniform(0.12, 0.19), 4)
                results.append(payload)
        except Exception as e:
            print(f"[DISLIKE SCROLL ERROR] {e}, falling back to small limit search")
            results = searcher.search(query=query_text, limit=abs_limit + 100)
            results.sort(key=lambda x: x.get('score', 0))
    else:
        results = searcher.search(query=query_text, limit=abs_limit + 10)

    final_results = []
    for res in results:
        isbn = res.get('isbn')
        if not isbn or (exclude_isbns and isbn in exclude_isbns):
            continue
            
        final_results.append({
            'isbn': isbn,
            'title': res.get('title'),
            'author': res.get('author'),
            'publisher': res.get('publisher', '미확인'),
            'cate_depth1': res.get('cate_depth1', ''),
            'similarity_score': round(float(res.get('score', 0)), 4),
        })
        if len(final_results) >= abs_limit:
            break
            
    return final_results


"""Cell 8: 단일 페르소나 매핑 함수"""

CHILD_KEYWORDS = {"어린이", "유아", "초등", "청소년"}

def map_books_for_persona(persona, book_vectors, idx_to_isbn, isbn_to_book, use_qdrant=True):
    """1명의 페르소나에 대해 READ/READING/INTERESTED 도서 매핑"""
    used_isbns = set()

    # 1. READ 20권
    q_read   = build_query_read(persona)
    if use_qdrant and HAS_QDRANT:
        read_books = get_books_from_qdrant(q_read, limit=20)
    else:
        vec_read = embed_text(q_read)
        if vec_read is None:
            read_books = []
        else:
            read_raw = topk_search(vec_read, book_vectors, idx_to_isbn, isbn_to_book, k=30, exclude_isbns=used_isbns)
            read_filtered = [b for b in read_raw if not any(any(kw in c for kw in CHILD_KEYWORDS) for c in parse_all_cates(b))]
            read_books = apply_genre_cap(read_filtered, max_per_genre=4)[:20]
    
    used_isbns.update(b['isbn'] for b in read_books)
    time.sleep(0.1)

    # 2. READING 3권
    q_reading = build_query_reading(persona)
    if use_qdrant and HAS_QDRANT:
        reading_books = get_books_from_qdrant(q_reading, limit=3, exclude_isbns=used_isbns)
    else:
        vec_reading = embed_text(q_reading)
        if vec_reading is None:
            reading_books = []
        else:
            reading_raw = topk_search(vec_reading, book_vectors, idx_to_isbn, isbn_to_book, k=10, exclude_isbns=used_isbns)
            reading_books = [b for b in reading_raw if not any(any(kw in c for kw in CHILD_KEYWORDS) for c in parse_all_cates(b))][:3]
    
    used_isbns.update(b['isbn'] for b in reading_books)
    time.sleep(0.1)

    # 3. INTERESTED 20권
    q_interested = build_query_interested(persona)
    if use_qdrant and HAS_QDRANT:
        interested_books = get_books_from_qdrant(q_interested, limit=20, exclude_isbns=used_isbns)
    else:
        vec_interested = embed_text(q_interested)
        if vec_interested is None:
            interested_books = []
        else:
            interested_raw = topk_search(vec_interested, book_vectors, idx_to_isbn, isbn_to_book, k=60, exclude_isbns=used_isbns)
            interested_filtered = [b for b in interested_raw if not any(any(kw in c for kw in CHILD_KEYWORDS) for c in parse_all_cates(b))]
            interested_books = apply_genre_cap(interested_filtered, max_per_genre=4)[:20]

    history = []
    for b in read_books:        history.append({**b, 'status': 'READ'})
    for b in reading_books:     history.append({**b, 'status': 'READING'})
    for b in interested_books:  history.append({**b, 'status': 'INTERESTED'})

    # 4. DISLIKE (관심 없음) 20권 추가
    # 전체 텍스트 기반으로 가장 관련 없는 도서 검색
    q_dislike = build_query_reading(persona) # 가장 복합적인 쿼리 사용
    if use_qdrant and HAS_QDRANT:
        dislike_books = get_books_from_qdrant(q_dislike, limit=-20, exclude_isbns=used_isbns)
        for b in dislike_books:
            history.append({**b, 'status': 'DISLIKE'})

    return history


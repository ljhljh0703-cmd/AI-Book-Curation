def merge_outputs(output_dir=OUTPUT_PATH, pattern='persona_full_result_'):
    import glob
    files = sorted(glob.glob(f'{output_dir}/{pattern}*.json'))

    if not files:
        print('병합할 파일 없음')
        return []

    merged = []
    seen_ids = set()

    for fp in files:
        with open(fp, 'r', encoding='utf-8') as f:
            data = json.load(f)
        for entry in data:
            pid = entry.get('persona_id')
            if pid not in seen_ids:
                merged.append(entry)
                seen_ids.add(pid)

    print(f'병합 완료: {len(files)}개 파일, 총 {len(merged)}명')

    final_path = f'{output_dir}/persona_book_history_final.json'
    with open(final_path, 'w', encoding='utf-8') as f:
        json.dump(merged, f, ensure_ascii=False, indent=2)

    print(f'최종 결과 저장: {final_path}')
    return merged



def join_list(value):
    if isinstance(value, list):
        return ', '.join(str(x) for x in value if x is not None)
    if value is None:
        return ''
    return str(value)

def get_best_intro(book, max_len=1200):
    for key in ['book_intro', 'simple_intro', 'description', 'pub_review', 'book_index']:
        v = book.get(key)
        if v:
            text = str(v).strip()
            if text:
                return text[:max_len]
    return ''

def make_document_text(book, max_intro=1200):
    title       = (book.get('title') or '').strip()
    author      = (book.get('author') or '').strip()
    publisher   = (book.get('publisher') or '').strip()
    pub_date    = (book.get('publish_date') or '').strip()
    categories  = book.get('categories') or book.get('cate_depth1') or []
    cate_depth1 = book.get('cate_depth1') or []
    kcid        = book.get('kcid') or []

    cate_text = join_list(categories) or join_list(cate_depth1)
    kcid_text = join_list(kcid)
    intro     = get_best_intro(book, max_intro)
    book_idx  = str(book.get('book_index') or '').strip()[:max_intro]
    pub_rev   = str(book.get('pub_review') or '').strip()[:max_intro]
    auth_intr = str(book.get('author_intro') or '').strip()[:max_intro]

    lines = [
        f'제목: {title}',
        f'저자: {author}',
        f'출판사: {publisher}',
        f'출간일: {pub_date}',
        f'카테고리: {cate_text}',
        f'KCID: {kcid_text}',
    ]
    if intro:     lines.append(f'소개: {intro}')
    if book_idx:  lines.append(f'목차: {book_idx}')
    if pub_rev:   lines.append(f'출판사 리뷰: {pub_rev}')
    if auth_intr: lines.append(f'저자 소개: {auth_intr}')

    return '\n'.join(l for l in lines if l and not l.endswith(': ')).strip()

def make_search_text(book):
    title = (book.get('title') or '').strip()
    cate  = join_list(book.get('cate_depth1') or [])
    intro = get_best_intro(book, max_len=300)
    return f'{title} {cate} {intro}'

import ast

# ── 어린이 필터 & 장르 캡 유틸 ──────────────────────────────
def parse_all_cates(book: dict) -> list:
    raw = book.get("cate_depth1") or ""
    if isinstance(raw, list):
        return [c.strip() for c in raw if c]
    try:
        parsed = ast.literal_eval(raw)
        if isinstance(parsed, list):
            return [c.strip() for c in parsed if c]
    except Exception:
        pass
    return [c.strip() for c in raw.split(',') if c.strip()]

def parse_cate_depth1(book: dict) -> str:
    cates = parse_all_cates(book)
    return cates[0] if cates else "기타"

def is_travel_book(book: dict) -> bool:
    return any("여행" in c for c in parse_all_cates(book))

def apply_genre_cap(books: list, max_per_genre: int = 4) -> list:
    CHILD_KEYWORDS = {"어린이", "유아", "초등", "청소년"}
    travel_count = 0
    genre_count = {}
    result = []
    for book in books:
        if any(any(kw in c for kw in CHILD_KEYWORDS) for c in parse_all_cates(book)):
            continue  # 어린이/유아/초등/청소년 책 완전 제거
        if is_travel_book(book):
            if travel_count < max_per_genre:
                result.append(book)
                travel_count += 1
            continue
        key = parse_cate_depth1(book)
        if key == "기타" or genre_count.get(key, 0) < max_per_genre:
            result.append(book)
            genre_count[key] = genre_count.get(key, 0) + 1
    return result


import re

def extract_keywords(persona):
    """
    persona_full_result JSON 구조에서 검색용 핵심 단어 추출
    """
    keywords = set()

    def tokenize(text):
        if not text: return []
        tokens = re.split(r'[\s,./·및]+', str(text))
        return [t.strip() for t in tokens if len(t.strip()) >= 2]

    # 페르소나 데이터 구조에 따라 필드 선택 필요
    # 기존 track_a/b/c 외에 book_history 같은 필드가 있다면 활용
    if 'track_a' in persona:
        for item in persona.get('track_a', []):
            keywords.update(tokenize(item))
    
    # 텍스트 형태의 특징이 있다면 추가
    for field in ['track_b', 'track_c']:
        if field in persona:
            for item in persona.get(field, []):
                content = item.split(':', 1)[-1] if ':' in item else item
                keywords.update(tokenize(content))

    stop_words = {
        '및', '기반', '통한', '활용', '이용', '관련', '위한',
        '통해', '에서', '으로', '하기', '하는', '있는', '없는',
        '미분류', '꾸준한', '체계적', '규칙적', '꾸준히',
    }
    keywords = {k for k in keywords if k not in stop_words and len(k) >= 2}
    return keywords


def prefilter_books(books, keywords, max_candidates=3000):
    """title + cate_depth1 + simple_intro에서 키워드 매칭 점수 상위 반환"""
    scored = []
    for book in books:
        search_text = make_search_text(book)
        score = sum(1 for kw in keywords if kw in search_text)
        if score > 0:
            scored.append((score, book))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [b for _, b in scored[:max_candidates]]


def build_global_candidate_pool(personas, books, max_candidates_per_persona=3000):
    """전체 100명 페르소나의 후보 도서 유니온 생성 (ISBN 기준 중복 제거)"""
    from tqdm import tqdm
    pool = {}  # isbn -> book
    for p in tqdm(personas, desc='후보 풀 구축'):
        kws = extract_keywords(p)
        candidates = prefilter_books(books, kws, max_candidates=max_candidates_per_persona)
        for b in candidates:
            isbn = str(b.get('isbn'))
            if isbn not in pool:
                pool[isbn] = b
    return list(pool.values())


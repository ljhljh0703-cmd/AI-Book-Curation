def embed_text(text, max_retries=5, base_delay=2.0):
    """단일 텍스트 임베딩. 실패 시 exponential backoff 재시도."""
    text = ' '.join(text.strip().split())
    if not text:
        return None

    delay = base_delay
    for attempt in range(1, max_retries + 1):
        try:
            result = client.feature_extraction(text, model=KURE_MODEL)
            if hasattr(result, 'tolist'):
                vector = result.tolist()
            else:
                vector = list(result)
            # 2D 배열인 경우 첫 번째 행 사용
            if vector and isinstance(vector[0], list):
                vector = vector[0]
            return vector
        except Exception as e:
            print(f'  [임베딩 오류] attempt={attempt}/{max_retries}: {e}')
            if attempt >= max_retries:
                return None
            time.sleep(min(delay, 60.0))
            delay *= 2
    return None

def cosine_similarity(a, b):
    a, b = np.array(a), np.array(b)
    denom = np.linalg.norm(a) * np.linalg.norm(b)
    if denom == 0:
        return 0.0
    return float(np.dot(a, b) / denom)


def build_embedding_cache(candidate_pool):
    """후보 풀 전체 임베딩. 실패 도서는 건너뜀."""
    vectors_list = []
    index = {}
    skipped = 0

    for i, book in enumerate(tqdm(candidate_pool, desc='도서 임베딩')):
        isbn = str(book.get('isbn'))
        doc  = make_document_text(book)
        vec  = embed_text(doc)

        if vec is None:
            skipped += 1
            continue

        idx = len(vectors_list)
        vectors_list.append(vec)
        index[isbn] = idx

        # 500권마다 중간 저장
        if (i + 1) % 500 == 0:
            tmp_vectors = np.array(vectors_list, dtype=np.float32)
            save_embedding_cache(tmp_vectors, index)
            print(f'  중간 저장: {i+1}/{len(candidate_pool)}, 스킵={skipped}')

        time.sleep(0.05)  # rate limit 방지

    vectors = np.array(vectors_list, dtype=np.float32)
    save_embedding_cache(vectors, index)
    print(f'\n임베딩 완료: {len(vectors_list)}권 성공, {skipped}권 스킵')
    return vectors, index


